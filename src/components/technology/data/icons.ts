// Logos that only come in one dark colour (black, navy), so they vanish on the dark tile.
const INVERT_ON_DARK = ["Express.js", "Render", "Netlify", "Buffer", "NativeWind", "BigCommerce", "Visa", "Razorpay", "Sentry", "Next.js"]
for (const name of INVERT_ON_DARK) TOOL_ICONS[name] = { ...TOOL_ICONS[name], invertOnDark: true }

const normalized = new Map(Object.keys(TOOL_ICONS).map((key) => [key.toLowerCase(), key]))
const keysByLength = Object.keys(TOOL_ICONS).sort((a, b) => b.length - a.length)

/**
 * Finds the logo for a tool name. An exact match wins; otherwise a name that starts with a known
 * brand uses that brand's logo, so "Meta Insights" shows Meta and "Google Identity" shows Google.
 */
export function findToolIcon(label: string): ToolIcon | undefined {
  const exact = normalized.get(label.trim().toLowerCase())
  if (exact) return TOOL_ICONS[exact]
  const lower = label.trim().toLowerCase()
  const brand = keysByLength.find((key) => lower.startsWith(`${key.toLowerCase()} `))
  return brand ? TOOL_ICONS[brand] : undefined
}
